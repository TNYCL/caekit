#!/usr/bin/env node
// Builds caekit-wasm for wasm32-unknown-unknown and assembles the npm package `caekit-wasm`
// in crates/caekit-wasm/npm/.
//
//   node crates/caekit-wasm/build.mjs [--check-size]
//
// The wasm-bindgen CLI must have the version of the `wasm-bindgen` crate in Cargo.lock. It
// is looked up in crates/caekit-wasm/.tools/, then on PATH. `--check-size` fails when the
// module is larger than SIZE_BUDGET.
//
// npm/ holds one .wasm (web/caekit_wasm_bg.wasm); the Node glue in node/ loads it from
// there. The package root resolves to the Node build under Node (ESM through
// node/caekit_wasm.mjs, require through node/caekit_wasm.js) and to the web build elsewhere.
import { spawnSync } from "node:child_process";
import { copyFileSync, cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..", "..");
const targetDir = path.resolve(process.env.CARGO_TARGET_DIR ?? path.join(root, "target"));
const wasm = path.join(targetDir, "wasm32-unknown-unknown", "release", "caekit_wasm.wasm");

// Budget of the shipped module in bytes, checked by `--check-size` (CI). The module measured
// 571,250 bytes when the budget was set (0.1.0, seven physics kinds). Raise the budget only
// together with a note of what made the module grow.
const SIZE_BUDGET = 700_000;

const NODE_WASM_PATH = "`${__dirname}/caekit_wasm_bg.wasm`";
const NODE_WASM_SHARED = "`${__dirname}/../web/caekit_wasm_bg.wasm`";

function fail(message) {
  console.error(`build.mjs: ${message}`);
  process.exit(1);
}

function run(command, args, env = process.env) {
  console.log(`+ ${[command, ...args].join(" ")}`);
  const result = spawnSync(command, args, { cwd: root, env, stdio: "inherit" });
  if (result.error) fail(`${command}: ${result.error.message}`);
  if (result.status !== 0) process.exit(result.status ?? 1);
}

function lockVersion() {
  const lock = readFileSync(path.join(root, "Cargo.lock"), "utf8");
  const match = /name = "wasm-bindgen"\r?\nversion = "([^"]+)"/.exec(lock);
  if (!match) fail("wasm-bindgen not found in Cargo.lock");
  return match[1];
}

function findCli(version) {
  const names = new Set(["wasm-bindgen", "wasm-bindgen.exe"]);
  const walk = (dir) => {
    for (const entry of existsSync(dir) ? readdirSync(dir) : []) {
      const file = path.join(dir, entry);
      if (statSync(file).isDirectory()) {
        const found = walk(file);
        if (found) return found;
      } else if (names.has(entry)) {
        return file;
      }
    }
    return undefined;
  };
  const cli = walk(path.join(here, ".tools")) ?? "wasm-bindgen";
  const probe = spawnSync(cli, ["--version"], { encoding: "utf8" });
  if (probe.error || probe.status !== 0) {
    fail(
      `wasm-bindgen CLI ${version} not found. Unpack the prebuilt release from ` +
        `https://github.com/wasm-bindgen/wasm-bindgen/releases/tag/${version} into ` +
        "crates/caekit-wasm/.tools/ (the version must equal Cargo.lock).",
    );
  }
  if (probe.stdout.trim().split(/\s+/).pop() !== version) {
    fail(`the CLI is '${probe.stdout.trim()}', Cargo.lock wants wasm-bindgen ${version}`);
  }
  return cli;
}

function workspaceVersion() {
  const manifest = readFileSync(path.join(root, "Cargo.toml"), "utf8");
  const match = /\[workspace\.package\][^[]*?\nversion = "([^"]+)"/.exec(manifest);
  if (!match) fail("workspace version not found in Cargo.toml");
  return match[1];
}

function writeJson(file, value) {
  writeFileSync(file, `${JSON.stringify(value, null, 2)}\n`);
}

// ESM entry for Node that re-exports the CommonJS glue, with no-op init functions so that
// code written for the web build (`await init()`) runs unchanged.
function nodeEsmWrapper(glue) {
  const names = [...new Set([...glue.matchAll(/^exports\.([A-Za-z_$][\w$]*) = /gm)].map((m) => m[1]))].sort();
  if (names.length === 0) fail("node glue: no exports found; the wasm-bindgen output changed");
  return [
    '// ESM entry of caekit-wasm under Node (the "node" condition of the package root).',
    "// The module is instantiated when it is imported; init() and initSync() do nothing and",
    "// exist so that code written for the web build runs unchanged. Generated by build.mjs.",
    'import caekit from "./caekit_wasm.js";',
    "",
    `export const { ${names.join(", ")} } = caekit;`,
    "",
    "export function initSync() {",
    "  return undefined;",
    "}",
    "",
    "export default async function init() {",
    "  return undefined;",
    "}",
    "",
  ].join("\n");
}

function assemble(staging) {
  const dest = path.join(here, "npm");
  rmSync(dest, { recursive: true, force: true });
  const webWasm = readFileSync(path.join(staging, "web", "caekit_wasm_bg.wasm"));
  const nodeWasm = readFileSync(path.join(staging, "node", "caekit_wasm_bg.wasm"));
  if (!webWasm.equals(nodeWasm)) {
    fail("the web and Node builds produced different modules; the package cannot share one");
  }
  cpSync(path.join(staging, "web"), path.join(dest, "web"), { recursive: true });
  cpSync(path.join(staging, "node"), path.join(dest, "node"), {
    recursive: true,
    filter: (source) => path.basename(source) !== "caekit_wasm_bg.wasm",
  });
  for (const dir of ["web", "node"]) rmSync(path.join(dest, dir, "package.json"), { force: true });

  const gluePath = path.join(dest, "node", "caekit_wasm.js");
  const glue = readFileSync(gluePath, "utf8");
  if (glue.split(NODE_WASM_PATH).length !== 2) {
    fail(`node glue: expected one ${NODE_WASM_PATH}; the wasm-bindgen output changed`);
  }
  const shared = glue.replace(NODE_WASM_PATH, NODE_WASM_SHARED);
  writeFileSync(gluePath, shared);
  writeFileSync(path.join(dest, "node", "caekit_wasm.mjs"), nodeEsmWrapper(shared));
  // The package root is "type": "module"; the Node glue is CommonJS.
  writeJson(path.join(dest, "node", "package.json"), { type: "commonjs" });
  for (const name of ["LICENSE-MIT", "LICENSE-APACHE"]) copyFileSync(path.join(root, name), path.join(dest, name));
  copyFileSync(path.join(here, "README.md"), path.join(dest, "README.md"));
  writeJson(path.join(dest, "package.json"), {
    name: "caekit-wasm",
    version: workspaceVersion(),
    description:
      "Multiphysics engineering simulation in browser and Node WebAssembly: solve versioned CAEKit models and read reproducible run reports.",
    license: "MIT OR Apache-2.0",
    author: "CAEKit contributors",
    repository: { type: "git", url: "git+https://github.com/caekit/caekit.git", directory: "crates/caekit-wasm" },
    homepage: "https://github.com/caekit/caekit/blob/master/docs/wasm.md",
    bugs: "https://github.com/caekit/caekit/issues",
    keywords: ["cae", "simulation", "fem", "multiphysics", "engineering", "wasm"],
    type: "module",
    main: "./web/caekit_wasm.js",
    module: "./web/caekit_wasm.js",
    types: "./web/caekit_wasm.d.ts",
    exports: {
      ".": {
        types: "./web/caekit_wasm.d.ts",
        node: { import: "./node/caekit_wasm.mjs", require: "./node/caekit_wasm.js" },
        default: "./web/caekit_wasm.js",
      },
      "./web": { types: "./web/caekit_wasm.d.ts", default: "./web/caekit_wasm.js" },
      "./node": { types: "./node/caekit_wasm.d.ts", default: "./node/caekit_wasm.js" },
      "./caekit_wasm_bg.wasm": "./web/caekit_wasm_bg.wasm",
      "./package.json": "./package.json",
    },
    // npm adds README.md by itself, but not license files with a suffix.
    files: ["web/", "node/", "LICENSE-MIT", "LICENSE-APACHE"],
    sideEffects: false,
    engines: { node: ">=18" },
  });
}

const args = process.argv.slice(2);
if (args.some((arg) => arg !== "--check-size")) fail("usage: node crates/caekit-wasm/build.mjs [--check-size]");

const cli = findCli(lockVersion());
run("cargo", ["build", "-p", "caekit-wasm", "--release", "--locked", "--target", "wasm32-unknown-unknown"], {
  ...process.env,
  CARGO_TARGET_DIR: targetDir,
  // Size-oriented release settings applied by environment, because the workspace profile
  // is shared with the native command-line tool.
  CARGO_PROFILE_RELEASE_OPT_LEVEL: "z",
  CARGO_PROFILE_RELEASE_LTO: "fat",
  CARGO_PROFILE_RELEASE_CODEGEN_UNITS: "1",
  CARGO_PROFILE_RELEASE_PANIC: "abort",
  CARGO_PROFILE_RELEASE_STRIP: "debuginfo",
});

const staging = path.join(here, "pkg");
rmSync(staging, { recursive: true, force: true });
for (const [target, dir] of [["web", "web"], ["nodejs", "node"]]) {
  const out = path.join(staging, dir);
  mkdirSync(out, { recursive: true });
  run(cli, [
    "--target", target, "--out-dir", out, "--out-name", "caekit_wasm",
    "--remove-name-section", "--remove-producers-section", wasm,
  ]);
}
assemble(staging);
rmSync(staging, { recursive: true, force: true });

const size = statSync(path.join(here, "npm", "web", "caekit_wasm_bg.wasm")).size;
console.log(`npm/: caekit-wasm ${workspaceVersion()}, module ${size.toLocaleString("en-US")} bytes`);
if (args.includes("--check-size")) {
  if (size > SIZE_BUDGET) {
    fail(`the module is ${size.toLocaleString("en-US")} bytes, budget ${SIZE_BUDGET.toLocaleString("en-US")} (SIZE_BUDGET)`);
  }
  console.log(`size check: ${size.toLocaleString("en-US")} of ${SIZE_BUDGET.toLocaleString("en-US")} bytes`);
}
